const domains = ["全部", ...new Set(questions.map((item) => item.domain))];
const levels = ["全部", "基础", "进阶"];
const levelRank = { "基础": 1, "进阶": 2 };
const state = {
  company: "all",
  domain: "全部",
  level: "全部",
  query: "",
  sort: "default"
};

const grid = document.querySelector("#questionGrid");
const template = document.querySelector("#questionTemplate");
const searchInput = document.querySelector("#searchInput");
const sortSelect = document.querySelector("#sortSelect");

renderFilterButtons("#domainFilters", domains, "domain");
renderFilterButtons("#levelFilters", levels, "level");
bindEvents();
render();

function q(domain, level, company, title, answer, tags) {
  return { domain, level, company, title, answer, tags };
}

function renderFilterButtons(selector, items, key) {
  const root = document.querySelector(selector);
  root.innerHTML = "";
  items.forEach((item) => {
    const button = document.createElement("button");
    button.type = "button";
    button.dataset.filter = key;
    button.dataset.value = item;
    button.textContent = item;
    if (item === "全部") button.classList.add("is-active");
    root.append(button);
  });
}

function bindEvents() {
  document.body.addEventListener("click", (event) => {
    const button = event.target.closest("button[data-filter]");
    if (!button) return;
    const { filter, value } = button.dataset;
    state[filter] = value;
    document.querySelectorAll(`button[data-filter="${filter}"]`).forEach((item) => {
      item.classList.toggle("is-active", item === button);
    });
    render();
  });

  searchInput.addEventListener("input", () => {
    state.query = searchInput.value.trim().toLowerCase();
    render();
  });

  sortSelect.addEventListener("change", () => {
    state.sort = sortSelect.value;
    render();
  });

  document.querySelector("#focusBig").addEventListener("click", () => setCompany("big"));
  document.querySelector("#focusSmall").addEventListener("click", () => setCompany("small"));
}

function setCompany(value) {
  state.company = value;
  document.querySelectorAll('button[data-filter="company"]').forEach((item) => {
    item.classList.toggle("is-active", item.dataset.value === value);
  });
  render();
}

function render() {
  const filtered = questions
    .filter((item) => state.company === "all" || item.company === state.company)
    .filter((item) => state.domain === "全部" || item.domain === state.domain)
    .filter((item) => state.level === "全部" || item.level === state.level)
    .filter(matchesQuery);

  const sorted = [...filtered].sort((a, b) => {
    if (state.sort === "level") return levelRank[a.level] - levelRank[b.level] || a.domain.localeCompare(b.domain, "zh-CN");
    if (state.sort === "domain") return a.domain.localeCompare(b.domain, "zh-CN") || levelRank[a.level] - levelRank[b.level];
    return questions.indexOf(a) - questions.indexOf(b);
  });

  grid.innerHTML = "";
  if (!sorted.length) {
    const empty = document.createElement("div");
    empty.className = "empty";
    empty.textContent = "没有匹配的题目，换一个方向或关键词试试。";
    grid.append(empty);
  } else {
    sorted.forEach(renderCard);
  }

  document.querySelector("#totalCount").textContent = sorted.length;
  document.querySelector("#bigCount").textContent = questions.filter((item) => item.company === "big").length;
  document.querySelector("#smallCount").textContent = questions.filter((item) => item.company === "small").length;
  document.querySelector("#domainCount").textContent = new Set(questions.map((item) => item.domain)).size;
  document.querySelector("#resultTitle").textContent = titleText();
  document.querySelector("#resultHint").textContent = `${state.domain === "全部" ? "全方向" : state.domain} · ${state.level} · ${companyText(state.company)}`;
}

function matchesQuery(item) {
  if (!state.query) return true;
  const haystack = [item.domain, item.level, item.title, item.answer, ...item.tags].join(" ").toLowerCase();
  return haystack.includes(state.query);
}

function renderCard(item) {
  const node = template.content.firstElementChild.cloneNode(true);
  node.classList.add(item.company);
  node.querySelector(".domain").textContent = item.domain;
  node.querySelector(".level").textContent = item.level;
  node.querySelector("h2").textContent = item.title;
  node.querySelector(".answer").textContent = item.answer;
  const tags = node.querySelector(".tags");
  [companyText(item.company), ...item.tags].forEach((tag) => {
    const span = document.createElement("span");
    span.textContent = tag;
    tags.append(span);
  });
  grid.append(node);
}

function companyText(value) {
  if (value === "big") return "大厂侧重";
  if (value === "small") return "小厂侧重";
  return "大厂 + 小厂";
}

function titleText() {
  if (state.company === "big") return "大厂高频题";
  if (state.company === "small") return "小厂实战题";
  return "全部题目";
}
